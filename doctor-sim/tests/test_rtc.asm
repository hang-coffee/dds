;; test_rtc.asm - RTC 设备手动模式读写测试
;; 期望最终 A = 0x12345678
;;
;; 流程:
;;   1. 设置 RTC 为 HALT=1 + TM=1（手动模式）
;;   2. 写入 2026-01-01 12:34:56
;;   3. 读回所有时间字段并逐一比较
;;   4. 全部匹配则 A=0x12345678，否则 A=0xDEADBEEF
;;
;;   A = 0x12345678

SECTION TEXT
ORG 0
;; 暂停并进入手动模式
LET A, BYTE 0x08
OUT BYTE 0x36, A
LET A, BYTE 0x10
OUT BYTE 0x36, A

;; 写入时间字段
LET A, BYTE 56
OUT BYTE 0x30, A
LET A, BYTE 34
OUT BYTE 0x31, A
LET A, BYTE 12
OUT BYTE 0x32, A
LET A, BYTE 1
OUT BYTE 0x33, A
OUT BYTE 0x34, A
LET A, WORD 2026
OUT WORD 0x35, A

;; 读回并比较
IN BYTE A, 0x30
SUB BYTE A, 56
LET E, DWORD FAIL
JRNZ BYTE A

IN BYTE A, 0x31
SUB BYTE A, 34
LET E, DWORD FAIL
JRNZ BYTE A

IN BYTE A, 0x32
SUB BYTE A, 12
LET E, DWORD FAIL
JRNZ BYTE A

IN BYTE A, 0x33
SUB BYTE A, 1
LET E, DWORD FAIL
JRNZ BYTE A

IN BYTE A, 0x34
SUB BYTE A, 1
LET E, DWORD FAIL
JRNZ BYTE A

IN WORD A, 0x35
SUB WORD A, 2026
LET E, DWORD FAIL
JRNZ WORD A

;; 通过
LET A, DWORD 0x12345678
HLT

FAIL:
LET A, DWORD 0xDEADBEEF
HLT
