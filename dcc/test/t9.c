/* t9.c - 复合赋值、++/--、三元、短路 && */   /* expect A = 0x0B */
int main(void) {
    int a;
    int b;
    int r;
    a = 10;
    b = 4;
    a += b;          /* 14 */
    a -= 2;          /* 12 */
    a *= 3;          /* 36 */
    a /= 4;          /* 9 */
    a %= 5;          /* 4 */
    a++;             /* 5 */
    ++a;             /* 6 */
    b = a--;         /* b=6, a=5 */
    r = (a > 3 && b < 10) ? a + b : 0;   /* 11 */
    return r;        /* 11 */
}
