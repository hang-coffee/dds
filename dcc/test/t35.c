/* t35.c - 64 位 long 移位（算术/逻辑、边界 31/32/33/63） */
/* expect A = 0x7F */
int main(void) {
    long a;
    unsigned long ua;
    int r = 0;

    a = 1;
    a = a << 63;                  /* 0x8000000000000000（符号位） */
    if (a < 0) r = r + 1;

    a = a >> 63;                  /* 算术右移 → -1 */
    if (a == -1) r = r + 2;

    ua = 1;
    ua = ua << 63;
    ua = ua >> 63;                /* 逻辑右移 → 1 */
    if (ua == 1) r = r + 4;

    a = 0x100000000;
    a = a >> 31;                  /* 2 */
    if (a == 2) r = r + 8;

    a = 0x100000000;
    a = a >> 32;                  /* 1 */
    if (a == 1) r = r + 16;

    a = 1;
    a = a << 32;                  /* 0x100000000 */
    if (a == 0x100000000) r = r + 32;

    a = 0x123456789;
    a = a >> 4;                   /* 0x12345678 */
    if (a == 0x12345678) r = r + 64;

    return r;                     /* 127 = 0x7F */
}
